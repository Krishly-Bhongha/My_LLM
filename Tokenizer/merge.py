# BUILD PAIR LOOKUP
# ============================================================

def build_pair_lookup(pair_ids):
    """
    pair_id -> slot

    Python dictionary gives O(1) average lookup.
    """

    return {
        int(pair_id): slot
        for slot, pair_id
        in enumerate(pair_ids)
    }


# ============================================================
# LOAD HEAP
# ============================================================

def load_heap(heap_array):
    """
    corpus.py saves heap entries as:

        [-frequency, pair_id]

    Convert them into a Python heapq heap.
    """

    heap = [
        (
            int(row[0]),
            int(row[1]),
        )
        for row in heap_array
    ]

    heapq.heapify(
        heap
    )

    return heap


# ============================================================
# PUSH UPDATED PAIR INTO HEAP
# ============================================================

def push_heap_entry(
    heap,
    pair_id,
    pair_to_slot,
    pair_counts,
):

    slot = pair_to_slot.get(
        int(pair_id)
    )

    if slot is None:

        return

    count = int(
        pair_counts[slot]
    )

    if count >= MIN_PAIR_FREQ_LOAD:

        heapq.heappush(
            heap,
            (
                -count,
                int(pair_id),
            ),
        )


# ============================================================
# GET HIGHEST-FREQUENCY PAIR
# ============================================================

def get_best_pair(
    heap,
    pair_to_slot,
    pair_counts,
):

    while heap:

        negative_count, pair_id = heap[0]

        slot = pair_to_slot.get(
            int(pair_id)
        )

        # Pair no longer exists.
        if slot is None:

            heapq.heappop(
                heap
            )

            continue

        current_count = int(
            pair_counts[slot]
        )

        stored_count = -int(
            negative_count
        )

        # ----------------------------------------------------
        # LAZY HEAP UPDATE
        # ----------------------------------------------------

        if stored_count != current_count:

            heapq.heappop(
                heap
            )

            continue

        if current_count < MIN_PAIR_FREQ:
            if current_count < MIN_PAIR_FREQ_LOAD:
                heapq.heappop(heap)
                continue

            return None, 0

        return (
            int(pair_id),
            current_count,
        )

    return None, 0


# ============================================================
# REMOVE OCCURRENCE
# ============================================================

def remove_occurrence(
    pair_id,
    node,
    pair_to_slot,
    pair_counts,
    pair_heads,
    pair_tails,
    occ_next,
    occ_prev,
    changed_pairs,
):

    pair_id = int(
        pair_id
    )

    node = int(
        node
    )

    slot = pair_to_slot.get(
        pair_id
    )

    if slot is None:

        return

    previous_occ = int(
        occ_prev[node]
    )

    next_occurrence = int(
        occ_next[node]
    )

    # --------------------------------------------------------
    # UPDATE PREVIOUS OCCURRENCE
    # --------------------------------------------------------

    if previous_occ != -1:

        occ_next[
            previous_occ
        ] = next_occurrence

    else:

        pair_heads[
            slot
        ] = next_occurrence

    # --------------------------------------------------------
    # UPDATE NEXT OCCURRENCE
    # --------------------------------------------------------

    if next_occurrence != -1:

        occ_prev[
            next_occurrence
        ] = previous_occ

    else:

        pair_tails[
            slot
        ] = previous_occ

    occ_prev[node] = -1
    occ_next[node] = -1

    pair_counts[
        slot
    ] -= 1

    changed_pairs.add(
        pair_id
    )


# ============================================================
# ADD OCCURRENCE
# ============================================================

def add_occurrence(
    pair_id,
    node,
    pair_to_slot,
    pair_ids,
    pair_counts,
    pair_heads,
    pair_tails,
    occ_next,
    occ_prev,
    changed_pairs,
):

    pair_id = int(
        pair_id
    )

    node = int(
        node
    )

    slot = pair_to_slot.get(
        pair_id
    )

    # --------------------------------------------------------
    # NEW PAIR TYPE
    # --------------------------------------------------------

    if slot is None:

        slot = len(
            pair_ids
        )

        pair_to_slot[
            pair_id
        ] = slot

        pair_ids.append(
            pair_id
        )

        pair_counts.append(
            0
        )

        pair_heads.append(
            -1
        )

        pair_tails.append(
            -1
        )

    # --------------------------------------------------------
    # APPEND TO OCCURRENCE LIST
    # --------------------------------------------------------

    tail = int(
        pair_tails[slot]
    )

    if tail == -1:

        pair_heads[
            slot
        ] = node

        pair_tails[
            slot
        ] = node

        occ_prev[node] = -1
        occ_next[node] = -1

    else:

        occ_next[
            tail
        ] = node

        occ_prev[
            node
        ] = tail

        occ_next[node] = -1

        pair_tails[
            slot
        ] = node

    pair_counts[
        slot
    ] += 1

    changed_pairs.add(
        pair_id
    )


# ============================================================
# MERGE ONE OCCURRENCE
# ============================================================

def merge_one_occurrence(
    left_node,
    merge_pair_id,
    new_token_id,
    pair_to_slot,
    pair_ids,
    pair_counts,
    pair_heads,
    pair_tails,
    tokens,
    next_node,
    prev_node,
    active,
    occ_next,
    occ_prev,
    changed_pairs,
):

    left_node = int(
        left_node
    )

    # --------------------------------------------------------
    # VALIDATE LEFT NODE
    # --------------------------------------------------------

    if not active[left_node]:

        return False

    right_node = int(
        next_node[left_node]
    )

    if right_node == -1:

        return False

    if not active[right_node]:

        return False

    # --------------------------------------------------------
    # VALIDATE PAIR
    # --------------------------------------------------------
    #
    # Important for overlapping pairs.
    #
    # Example:
    #
    #     A A A
    #
    # When the first A+A is merged, the second occurrence
    # can become stale. We therefore verify it before merging.

    actual_pair = encode_pair(
        tokens[left_node],
        tokens[right_node],
    )

    if actual_pair != int(
        merge_pair_id
    ):

        return False

    # --------------------------------------------------------
    # SAVE NEIGHBORS
    # --------------------------------------------------------

    left_neighbor = int(
        prev_node[left_node]
    )

    right_neighbor = int(
        next_node[right_node]
    )

    # --------------------------------------------------------
    # REMOVE (LEFT_NEIGHBOR, LEFT)
    # --------------------------------------------------------

    if left_neighbor != -1:

        old_pair = encode_pair(
            tokens[left_neighbor],
            tokens[left_node],
        )

        remove_occurrence(
            old_pair,
            left_neighbor,
            pair_to_slot,
            pair_counts,
            pair_heads,
            pair_tails,
            occ_next,
            occ_prev,
            changed_pairs,
        )

    # --------------------------------------------------------
    # REMOVE (LEFT, RIGHT)
    # --------------------------------------------------------

    remove_occurrence(
        merge_pair_id,
        left_node,
        pair_to_slot,
        pair_counts,
        pair_heads,
        pair_tails,
        occ_next,
        occ_prev,
        changed_pairs,
    )

    # --------------------------------------------------------
    # REMOVE (RIGHT, RIGHT_NEIGHBOR)
    # --------------------------------------------------------

    if right_neighbor != -1:

        old_pair = encode_pair(
            tokens[right_node],
            tokens[right_neighbor],
        )

        remove_occurrence(
            old_pair,
            right_node,
            pair_to_slot,
            pair_counts,
            pair_heads,
            pair_tails,
            occ_next,
            occ_prev,
            changed_pairs,
        )

    # --------------------------------------------------------
    # MERGE
    # --------------------------------------------------------

    tokens[
        left_node
    ] = new_token_id

    # Remove right node from linked list.

    next_node[
        left_node
    ] = right_neighbor

    if right_neighbor != -1:

        prev_node[
            right_neighbor
        ] = left_node

    active[
        right_node
    ] = False

    next_node[
        right_node
    ] = -1

    prev_node[
        right_node
    ] = -1

    # --------------------------------------------------------
    # ADD (LEFT_NEIGHBOR, NEW_TOKEN)
    # --------------------------------------------------------

    if left_neighbor != -1:

        new_pair = encode_pair(
            tokens[left_neighbor],
            new_token_id,
        )

        add_occurrence(
            new_pair,
            left_neighbor,
            pair_to_slot,
            pair_ids,
            pair_counts,
            pair_heads,
            pair_tails,
            occ_next,
            occ_prev,
            changed_pairs,
        )

    # --------------------------------------------------------
    # ADD (NEW_TOKEN, RIGHT_NEIGHBOR)
    # --------------------------------------------------------

    if right_neighbor != -1:

        new_pair = encode_pair(
            new_token_id,
            tokens[right_neighbor],
        )

        add_occurrence(
            new_pair,
            left_node,
            pair_to_slot,
            pair_ids,
            pair_counts,
            pair_heads,
            pair_tails,
            occ_next,
            occ_prev,
            changed_pairs,
        )

    return True


# ============================================================
# MERGE ALL OCCURRENCES
# ============================================================

def merge_pair(
    merge_pair_id,
    new_token_id,
    pair_to_slot,
    pair_ids,
    pair_counts,
    pair_heads,
    pair_tails,
    tokens,
    next_node,
    prev_node,
    active,
    occ_next,
    occ_prev,
    heap,
):

    slot = pair_to_slot.get(
        int(merge_pair_id)
    )

    if slot is None:

        return 0

    current_node = int(
        pair_heads[slot]
    )

    merged_count = 0

    # Every pair whose count changes during this merge goes
    # into this set.
    #
    # Therefore we NEVER scan all pair types just to update
    # the heap.

    changed_pairs = set()

    while current_node != -1:

        # Save before modifying occurrence links.
        next_occurrence = int(
            occ_next[current_node]
        )

        success = merge_one_occurrence(
            current_node,
            merge_pair_id,
            new_token_id,
            pair_to_slot,
            pair_ids,
            pair_counts,
            pair_heads,
            pair_tails,
            tokens,
            next_node,
            prev_node,
            active,
            occ_next,
            occ_prev,
            changed_pairs,
        )

        if success:

            merged_count += 1

        current_node = next_occurrence

    # --------------------------------------------------------
    # SELECTED PAIR IS NOW EMPTY
    # --------------------------------------------------------

    slot = pair_to_slot.get(
        int(merge_pair_id)
    )

    if slot is not None:

        pair_counts[
            slot
        ] = 0

        pair_heads[
            slot
        ] = -1

        pair_tails[
            slot
        ] = -1

    # --------------------------------------------------------
    # UPDATE HEAP
    # --------------------------------------------------------
    #
    # Only changed pair types are touched.
    #
    # Old heap entries remain there and are removed lazily
    # by get_best_pair().

    for pair_id in changed_pairs:

        push_heap_entry(
            heap,
            pair_id,
            pair_to_slot,
            pair_counts,
        )

    return merged_count


# ============================================================
# SAVE CHECKPOINT
# ============================================================

def save_checkpoint(
    completed_merges,
    tokens,
    next_node,
    prev_node,
    active,
    offsets,
    pair_ids,
    pair_counts,
    pair_heads,
    pair_tails,
    occ_next,
    occ_prev,
    heap,
    merges,
    vocab,
):
    """
    Safely save the latest BPE checkpoint.

    Only one completed checkpoint is kept:

        checkpoints/latest/

    A temporary checkpoint is completely written and verified
    before replacing the previous checkpoint.

    If the program is interrupted during saving, the previous
    checkpoint remains recoverable.
    """

    print(
        f"\nSaving checkpoint after "
        f"{completed_merges:,} merges..."
    )

    CHECKPOINT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    # --------------------------------------------------------
    # CLEAN OLD TEMPORARY DIRECTORIES
    # --------------------------------------------------------

    if TEMP_CHECKPOINT_DIR.exists():

        shutil.rmtree(
            TEMP_CHECKPOINT_DIR
        )

    if OLD_CHECKPOINT_DIR.exists():

        shutil.rmtree(
            OLD_CHECKPOINT_DIR
        )

    TEMP_CHECKPOINT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    files = checkpoint_files(
        TEMP_CHECKPOINT_DIR
    )

    # --------------------------------------------------------
    # CONVERT DYNAMIC PAIR STRUCTURES
    # --------------------------------------------------------

    pair_ids_array = np.asarray(
        pair_ids,
        dtype=np.int64,
    )

    pair_counts_array = np.asarray(
        pair_counts,
        dtype=np.int64,
    )

    pair_heads_array = np.asarray(
        pair_heads,
        dtype=OFFSET_DTYPE,
    )

    pair_tails_array = np.asarray(
        pair_tails,
        dtype=OFFSET_DTYPE,
    )

    # --------------------------------------------------------
    # SAVE NUMPY FILES
    # --------------------------------------------------------

    save_numpy(
        tokens,
        files["tokens"],
    )

    save_numpy(
        next_node,
        files["next"],
    )

    save_numpy(
        prev_node,
        files["prev"],
    )

    save_numpy(
        active,
        files["active"],
    )

    save_numpy(
        offsets,
        files["offsets"],
    )

    save_numpy(
        pair_ids_array,
        files["pair_ids"],
    )

    save_numpy(
        pair_counts_array,
        files["pair_counts"],
    )

    save_numpy(
        pair_heads_array,
        files["pair_heads"],
    )

    save_numpy(
        pair_tails_array,
        files["pair_tails"],
    )

    save_numpy(
        occ_next,
        files["occ_next"],
    )

    save_numpy(
        occ_prev,
        files["occ_prev"],
    )

    # --------------------------------------------------------
    # SAVE HEAP
    # --------------------------------------------------------

    heap_array = np.asarray(
        heap,
        dtype=np.int64,
    )

    save_numpy(
        heap_array,
        files["heap"],
    )

    # --------------------------------------------------------
    # SAVE MERGE HISTORY
    # --------------------------------------------------------

    save_json(
        merges,
        files["merges"],
    )

    # --------------------------------------------------------
    # SAVE VOCABULARY
    # --------------------------------------------------------

    save_json(
        vocab,
        files["vocab"],
    )

    # --------------------------------------------------------
    # VERIFY TEMPORARY CHECKPOINT
    # --------------------------------------------------------

    for path in files.values():

        if not path.exists():

            raise RuntimeError(
                "Checkpoint file missing:\n"
                f"{path}"
            )

    # --------------------------------------------------------
    # SAFELY REPLACE PREVIOUS CHECKPOINT
    # --------------------------------------------------------

    if LATEST_CHECKPOINT_DIR.exists():

        # Move old valid checkpoint out of the way.
        os.replace(
            LATEST_CHECKPOINT_DIR,
            OLD_CHECKPOINT_DIR,
        )

    # Move the completely written checkpoint into place.
    os.replace(
        TEMP_CHECKPOINT_DIR,
        LATEST_CHECKPOINT_DIR,
    )

    # --------------------------------------------------------
    # UPDATE MERGE STATE LAST
    # --------------------------------------------------------

    save_json(
        {
            "completed_merges": completed_merges,
            "checkpoint": "checkpoints/latest",
        },
        MERGE_STATE_FILE,
    )

    # --------------------------------------------------------
    # OLD CHECKPOINT NO LONGER NEEDED
    # --------------------------------------------------------

    if OLD_CHECKPOINT_DIR.exists():

        shutil.rmtree(
            OLD_CHECKPOINT_DIR
        )

    print(
        "Checkpoint saved."
    )

