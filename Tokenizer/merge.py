# ============================================================
# VALIDATE STATE
# ============================================================

def validate_state(
    tokens,
    next_node,
    prev_node,
    active,
    offsets,
    pair_ids,
    pair_counts,
    pair_heads,
    pair_tails,
    occ_next,
    occ_prev,
):

    node_count = len(tokens)

    for array in (
        next_node,
        prev_node,
        active,
        occ_next,
        occ_prev,
    ):

        if len(array) != node_count:

            raise RuntimeError(
                "Node arrays have inconsistent lengths."
            )

    pair_count = len(
        pair_ids
    )

    if len(pair_counts) != pair_count:
        raise RuntimeError(
            "pair_counts length mismatch."
        )

    if len(pair_heads) != pair_count:
        raise RuntimeError(
            "pair_heads length mismatch."
        )

    if len(pair_tails) != pair_count:
        raise RuntimeError(
            "pair_tails length mismatch."
        )

    if len(offsets) == 0:

        raise RuntimeError(
            "offsets.npy is empty."
        )


