def load_merge_state():
    """
    Return:

        completed_merges
        checkpoint_directory

    If no checkpoint has been created yet, return:

        0, None

    In that case, the initial files generated by corpus.py
    are loaded directly from DATASET_DIR.
    """

    if not MERGE_STATE_FILE.exists():

        return 0, None

    state = load_json(
        MERGE_STATE_FILE
    )

    completed_merges = int(
        state.get(
            "completed_merges",
            0,
        )
    )

    checkpoint_name = state.get(
        "checkpoint",
        None,
    )

    if checkpoint_name is None:

        return completed_merges, None

    checkpoint_path = (
        DATASET_DIR
        / checkpoint_name
    )

    return completed_merges, checkpoint_path


