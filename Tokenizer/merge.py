# MAIN BPE LOOP
# ============================================================

def run_bpe():

    print("=" * 60)
    print("BPE MERGE ENGINE")
    print("=" * 60)

    # --------------------------------------------------------
    # LOAD STATE
    # --------------------------------------------------------

    (
        completed_merges,
        tokens,
        next_node,
        prev_node,
        active,
        offsets,
        pair_ids,
        pair_counts,
        pair_heads,
        pair_tails,
        occ_next,
        occ_prev,
        heap_array,
        merges,
        checkpoint_vocab,
    ) = load_state()

    # --------------------------------------------------------
    # LOAD CORRECT VOCABULARY
    # --------------------------------------------------------

    if checkpoint_vocab is not None:

        vocab = checkpoint_vocab

    else:

        vocab = load_json(
            VOCAB_FILE
        )

    reverse_vocab = {
        int(token_id): token
        for token, token_id
        in vocab.items()
    }

    print(
        f"Vocabulary size: "
        f"{len(vocab):,}"
    )

    validate_state(
        tokens,
        next_node,
        prev_node,
        active,
        offsets,
        pair_ids,
        pair_counts,
        pair_heads,
        pair_tails,
        occ_next,
        occ_prev,
    )

    # --------------------------------------------------------
    # PAIR LISTS
    # --------------------------------------------------------

    pair_ids = [
        int(x)
        for x in pair_ids
    ]

    pair_counts = [
        int(x)
        for x in pair_counts
    ]

    pair_heads = [
        int(x)
        for x in pair_heads
    ]

    pair_tails = [
        int(x)
        for x in pair_tails
    ]

    # --------------------------------------------------------
    # PAIR LOOKUP
    # --------------------------------------------------------

    print(
        "\nBuilding pair lookup..."
    )

    pair_to_slot = build_pair_lookup(
        pair_ids
    )

    print(
        f"Unique pair types: "
        f"{len(pair_ids):,}"
    )

    # --------------------------------------------------------
    # HEAP
    # --------------------------------------------------------

    print(
        "\nLoading heap..."
    )

    heap = load_heap(
        heap_array
    )

    print(
        f"Heap entries: "
        f"{len(heap):,}"
    )

    # --------------------------------------------------------
    # CHECK MERGE HISTORY
    # --------------------------------------------------------

    if len(merges) != completed_merges:

        raise RuntimeError(
            "merge_state.json and merges.json "
            "disagree about completed merges."
        )

    # --------------------------------------------------------
    # MAIN LOOP
    # --------------------------------------------------------

    while completed_merges < NUM_MERGES:

        pair_id, frequency = get_best_pair(
            heap,
            pair_to_slot,
            pair_counts,
        )

        if pair_id is None:

            print(
                "\nNo pair satisfies MIN_PAIR_FREQ."
            )

            break

        left_id, right_id = decode_pair(
            pair_id
        )

        # ----------------------------------------------------
        # TOKEN STRINGS
        # ----------------------------------------------------

        left_token = reverse_vocab.get(
            left_id
        )

        right_token = reverse_vocab.get(
            right_id
        )

        if left_token is None:

            raise RuntimeError(
                f"Token ID {left_id} "
                f"is missing from vocabulary."
            )

        if right_token is None:

            raise RuntimeError(
                f"Token ID {right_id} "
                f"is missing from vocabulary."
            )

        # ----------------------------------------------------
        # SPECIAL TOKEN SAFETY
        # ----------------------------------------------------

        if (
            left_token in DO_NOT_MERGE
            or right_token in DO_NOT_MERGE
        ):

            # This should never happen because corpus.py filters
            # these pairs, but it protects against a corrupt state.

            heapq.heappop(
                heap
            )

            continue

        # ----------------------------------------------------
        # NEW TOKEN
        # ----------------------------------------------------

        new_token = (
            left_token
            + right_token
        )

        if new_token in vocab:

            new_token_id = int(
                vocab[new_token]
            )

        else:

            new_token_id = len(
                vocab
            )

            if new_token_id >= MAX_VOCAB_SIZE:

                print(
                    "\nMaximum vocabulary size reached."
                )

                break

            vocab[
                new_token
            ] = new_token_id

            reverse_vocab[
                new_token_id
            ] = new_token

        # ----------------------------------------------------
        # DISPLAY
        # ----------------------------------------------------

        print(
            f"\nMerge "
            f"{completed_merges + 1:,}/"
            f"{NUM_MERGES:,}"
        )

        print(
            f"  Frequency : {frequency:,}"
        )

        print(
            f"  Pair      : "
            f"{left_token!r} + {right_token!r}"
        )

        print(
            f"  New token : {new_token!r}"
        )

        # ----------------------------------------------------
        # PERFORM MERGE
        # ----------------------------------------------------

        merged_count = merge_pair(
            pair_id,
            new_token_id,
            pair_to_slot,
            pair_ids,
            pair_counts,
            pair_heads,
            pair_tails,
            tokens,
            next_node,
            prev_node,
            active,
            occ_next,
            occ_prev,
            heap,
        )

        # ----------------------------------------------------
        # STALE PAIR
        # ----------------------------------------------------

        if merged_count == 0:

            heapq.heappop(
                heap
            )

            continue

        completed_merges += 1

        # ----------------------------------------------------
        # SAVE MERGE RULE
        # ----------------------------------------------------

        merges.append(
            [
                left_id,
                right_id,
                new_token_id,
            ]
        )

        print(
            f"  Occurrences: "
            f"{merged_count:,}"
        )

        # ----------------------------------------------------
        # CHECKPOINT
        # ----------------------------------------------------

        if (
            completed_merges
            % CHECKPOINT_INTERVAL
            == 0
        ):

            save_checkpoint(
                completed_merges,
                tokens,
                next_node,
                prev_node,
                active,
                offsets,
                pair_ids,
                pair_counts,
                pair_heads,
                pair_tails,
                occ_next,
                occ_prev,
                heap,
                merges,
                vocab,
            )

    # --------------------------------------------------------
    # FINAL SAVE
    # --------------------------------------------------------

    print(
        "\nSaving final state..."
    )

    save_checkpoint(
        completed_merges,
        tokens,
        next_node,
        prev_node,
        active,
        offsets,
        pair_ids,
        pair_counts,
        pair_heads,
        pair_tails,
        occ_next,
        occ_prev,
        heap,
        merges,
        vocab,
    )

    # --------------------------------------------------------
    # SUMMARY
    # --------------------------------------------------------

    print()
    print("=" * 60)
    print("BPE MERGING COMPLETE")
    print("=" * 60)

    print(
        f"Completed merges : "
        f"{completed_merges:,}"
    )

    print(
        f"Vocabulary size  : "
        f"{len(vocab):,}"
    )

    print(
        f"Merge rules      : "
        f"{len(merges):,}"
    )


# ============================================================
