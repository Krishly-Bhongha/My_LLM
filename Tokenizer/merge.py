# ============================================================
# PAIR ENCODING
# ============================================================

def encode_pair(left, right):
    """
    Convert two token IDs into one unique integer pair ID.
    """

    return (
        int(left) * int(PAIR_BASE)
        + int(right)
    )


def decode_pair(pair_id):
    """
    Convert pair ID back into:

        left_token_id, right_token_id
    """

    pair_id = int(pair_id)

    return (
        pair_id // int(PAIR_BASE),
        pair_id % int(PAIR_BASE),
    )


